require('dotenv').config();
const express=require('express');const cors=require('cors');const morgan=require('morgan');const path=require('path');
const connectDB=require('./config/db');const {errorHandler}=require('./middleware/errorHandler');
const app=express();
app.use(cors({origin:process.env.CLIENT_URL||'*'}));app.use(express.json({limit:'10mb'}));app.use(morgan('dev'));
app.use('/uploads',express.static(path.join(__dirname,'uploads')));
app.get('/api/health',(req,res)=>res.json({ok:true}));
app.use('/api/auth',require('./routes/auth'));app.use('/api/users',require('./routes/users'));
app.use('/api/locations',require('./routes/locations'));app.use('/api/categories',require('./routes/categories'));
app.use('/api/standards',require('./routes/standards'));app.use('/api/inspections',require('./routes/inspections'));
app.use('/api/issues',require('./routes/issues'));app.use('/api/dashboard',require('./routes/dashboard'));app.use('/api/reports',require('./routes/reports'));
app.use(errorHandler);
const PORT=process.env.PORT||5000;connectDB().then(()=>app.listen(PORT,()=>console.log('Server on '+PORT)));
